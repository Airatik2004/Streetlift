/** Возрастной дивизион ISF; [ages] — допустимый возраст (null — любой). */
enum class Division(val title: String, val ages: IntRange?) {
    ALL("все возраста", null),
    YOUTH("юноши, 13–17 лет", 13..17),
    JUNIOR("юниоры, 18–22 года", 18..22),
    VETERAN("ветераны, 40+", 40..200),
    AMATEUR("открытая, любители", 18..200),
    PRO("открытая, профессионалы", 18..200);

    /** Подходит ли дивизион по возрасту (возраст неизвестен — подходит любой). */
    fun fits(age: Int?): Boolean = age == null || ages == null || age in ages
}

/** Вид соревновательного результата. */
enum class CompKind(val title: String) {
    MAX("На максимум, 1 раз"),
    REPS("На повторы с весом"),
    REPS_BW("На повторы без веса"),
}

/** Упражнение программы, к которому относится дисциплина. */
enum class CompLift(val exerciseName: String, val short: String) {
    PULL("Подтягивания", "подтягивания"),
    DIP("Отжимания на брусьях", "брусья"),
    MUSCLE_UP("Выходы силой", "выход силой"),
}

/**
 * Соревновательная дисциплина: что максимизируем к дате.
 * [weights] — вес для каждого упражнения (для REPS — фиксированный, для MAX — не задан).
 */
data class Discipline(
    val id: String,
    val title: String,
    val kind: CompKind,
    val lifts: List<CompLift>,
    val weights: List<Float> = emptyList(),
    val divisions: List<Division> = listOf(Division.ALL),
    val table: Standards.Table? = null,
) {
    val isTotal: Boolean get() = lifts.size > 1
    val unit: String get() = if (kind == CompKind.MAX) "кг" else "повт."

    fun fits(age: Int?): Boolean = divisions.any { it.fits(age) }

    companion object {
        private val P = CompLift.PULL
        private val D = CompLift.DIP
        private val M = CompLift.MUSCLE_UP
        private val V = listOf(Division.JUNIOR, Division.VETERAN)

