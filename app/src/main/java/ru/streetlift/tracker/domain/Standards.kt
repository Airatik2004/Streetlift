    }

    /** Строка таблицы: весовая категория «до [maxKg]» (null — «+») и значения по разрядам (null — нет норматива). */
    data class Row(val maxKg: Float?, val values: List<Float?>)

    data class Table(val federation: String, val ranks: List<Rank>, val rows: List<Row>) {
        /** Подпись весовой категории: «до 75 кг» или «90+ кг». */
        fun label(row: Row): String {
            row.maxKg?.let { return "до ${Fmt.step(it)} кг" }
            val prev = rows.mapNotNull { it.maxKg }.maxOrNull() ?: 0f
            return "${Fmt.step(prev)}+ кг"
        }

        /** Весовая категория для своего веса. */
        fun rowFor(bodyWeight: Float): Row = rows.firstOrNull { it.maxKg != null && bodyWeight <= it.maxKg + 0.001f } ?: rows.last()

        /** Лучший выполненный разряд и следующий (с нормативом) для результата [result]. */
        fun evaluate(bodyWeight: Float, result: Float): Pair<Pair<Rank, Float>?, Pair<Rank, Float>?> {
            val row = rowFor(bodyWeight)
            // Разряды по возрастанию сложности: с конца таблицы к началу
            val pairs = ranks.zip(row.values).mapNotNull { (r, v) -> v?.let { r to it } }
            val done = pairs.firstOrNull { result >= it.second - 0.001f }
            val next = if (done == null) pairs.lastOrNull() else pairs.getOrNull(pairs.indexOf(done) - 1)
            return done to next
        }
    }

    /** Таблица из строк «вк;значения…» (вк «+» — последняя категория). Значения «-» — нет норматива. */
    private fun table(federation: String, ranks: String, data: String): Table {
        val rs = ranks.split(';').map { t -> Rank.entries.first { it.name == t } }
        val rows = data.trim().lines().map { line ->
            val p = line.trim().split(';')
            val max = p[0].takeIf { it != "+" }?.replace(',', '.')?.toFloat()
            val row = Row(max, p.drop(1).map { v -> v.takeIf { it != "-" }?.replace(',', '.')?.toFloat() })
            require(row.values.size == rs.size) { "таблица $federation: ${line}" }
            row
        }
        return Table(federation, rs, rows)
    }

